                            <div id="tab-content-1" class="container tab-pane active">
                                Siyazigabisa Home of Hope is an orphanage and community center for children located about 25 kilometers north of Johannesburg, in a township called Thembisa.
                                The founder of the home, Gabisile Khoza, has a strong determination and will-power to provide her children with the best situation possible.
                                She started the home in response to the violence and abuse occurring in the township.
                                She welcomed and continues to invite abandoned and abused children, and abused women.
                                She helps counsel these women and children that feel torn from these experiences and have had many trials and tribulations.
                                The name <b>Siyazigabisa</b> means to be proud of who you are. This is the goal that Gabisile has: <i>that everyone can feel more confident and sure of themselves.</i>
                            </div>
                            <div id="tab-content-2" class="container tab-pane fade">
                                Our mission is to restore hope and dignity to disadvantaged
                                individuals and families by delivering compassionate, practical
                                support across food security, healthcare, education and safe housing.
                                We are committed to building a strong, caring community where no
                                person is left behind — regardless of their background or
                                circumstances. Every life matters to us, and we will continue
                                fighting to make that a reality for the people we serve.
                            </div>
                            <div id="tab-content-3" class="container tab-pane fade">
                                We envision a South Africa where every person has access to the
                                basic necessities of life — food, clean water, shelter, healthcare
                                and education. A society where vulnerable communities are empowered
                                to break the cycle of poverty and build sustainable futures for
                                themselves and their children. Siyazigabisa Home Of Hope strives
                                to be a beacon of lasting change, driven by love, unity and
                                unwavering hope.
